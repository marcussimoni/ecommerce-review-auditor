CREATE TABLE IF NOT EXISTS avaliacoes_produto (
                                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                  produto_id VARCHAR(64) NOT NULL,
    nome_produto VARCHAR(160) NOT NULL,
    vendedor_id VARCHAR(64),
    estrelas INT NOT NULL CHECK (estrelas BETWEEN 1 AND 5),
    comentario VARCHAR(2000) NOT NULL,
    data_avaliacao TIMESTAMP DEFAULT CURRENT_TIMESTAMP
    );

CREATE INDEX IF NOT EXISTS idx_avaliacoes_produto_id
    ON avaliacoes_produto (produto_id);

CREATE TABLE IF NOT EXISTS relatorios_revisao (
                                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                  produto_id VARCHAR(64) NOT NULL,
    motivo_revisao VARCHAR(120) NOT NULL,
    resumo_analise VARCHAR(2000) NOT NULL,
    total_avaliacoes_analisadas INT NOT NULL,
    avaliacoes_fatores_externos INT NOT NULL,
    criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP
    );