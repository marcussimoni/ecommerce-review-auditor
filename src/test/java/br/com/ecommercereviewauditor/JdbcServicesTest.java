package br.com.ecommercereviewauditor;

import br.com.ecommercereviewauditor.config.DatabaseConfig;
import br.com.ecommercereviewauditor.entities.AvaliacaoDivergente;
import br.com.ecommercereviewauditor.entities.RelatorioRevisao;
import br.com.ecommercereviewauditor.service.AvaliacaoJdbcService;
import br.com.ecommercereviewauditor.service.RelatorioJdbcService;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.List;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.*;

class JdbcServicesTest {

    private DatabaseConfig databaseConfig;
    private AvaliacaoJdbcService avaliacaoService;
    private RelatorioJdbcService relatorioService;

    @BeforeEach
    void configurarBancoEmMemoria() throws SQLException {
        String dbName = "test_db_" + UUID.randomUUID().toString().replace("-", "");
        String jdbcUrl = "jdbc:h2:mem:" + dbName + ";DB_CLOSE_DELAY=-1";

        databaseConfig = new DatabaseConfig() {
            @Override
            public Connection getConnection() throws SQLException {
                return java.sql.DriverManager.getConnection(jdbcUrl, "sa", "");
            }
        };

        criarTabelasESeeds(jdbcUrl);

        avaliacaoService = new AvaliacaoJdbcService(databaseConfig);
        relatorioService = new RelatorioJdbcService(databaseConfig);
    }

    private void criarTabelasESeeds(String jdbcUrl) throws SQLException {
        try (Connection conn = java.sql.DriverManager.getConnection(jdbcUrl, "sa", "");
             Statement st = conn.createStatement()) {

            st.execute("""
                    CREATE TABLE avaliacoes_produto (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        produto_id VARCHAR(50) NOT NULL,
                        nome_produto VARCHAR(200) NOT NULL,
                        vendedor_id VARCHAR(50) NOT NULL,
                        estrelas INT NOT NULL,
                        comentario TEXT NOT NULL,
                        criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                    )
                    """);

            st.execute("""
                    CREATE TABLE relatorios_revisao (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        produto_id VARCHAR(50) NOT NULL,
                        motivo_revisao VARCHAR(255) NOT NULL,
                        resumo_analise TEXT NOT NULL,
                        total_avaliacoes_analisadas INT NOT NULL,
                        avaliacoes_fatores_externos INT NOT NULL,
                        avaliacoes_divergentes_ids VARCHAR(255),
                        detalhes_divergencias TEXT,
                        criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                    )
                    """);

            st.execute("""
                    INSERT INTO avaliacoes_produto (produto_id, nome_produto, vendedor_id, estrelas, comentario)
                    VALUES
                        ('PROD-001', 'Cafeteira Elétrica', 'SELL-01', 5, 'Excelente café e rápida'),
                        ('PROD-001', 'Cafeteira Elétrica', 'SELL-01', 1, 'Caixa amassada, mas funciona bem'),
                        ('PROD-002', 'Fone Bluetooth', 'SELL-02', 1, 'Parou de ligar após dois dias')
                    """);
        }
    }

    // --- RelatorioJdbcService ---

    @Test
    void deveSalvarRelatorioFiltrandoApenasFatoresExternosReais() {
        List<AvaliacaoDivergente> mistas = List.of(
                new AvaliacaoDivergente(2L, 1, "SELL-01", "EMBALAGEM", "Caixa amassada, produto íntegro"),
                new AvaliacaoDivergente(99L, 1, "SELL-01", "DEFEITO_PRODUTO", "Deve ser ignorado")
        );

        RelatorioRevisao salvo = relatorioService.salvarRelatorio(
                "PROD-001",
                "EMBALAGEM",
                "Uma avaliação aponta avaria na embalagem.",
                2,
                2,
                mistas
        );

        assertNotNull(salvo.id());
        assertEquals("PROD-001", salvo.produtoId());
        assertEquals("EMBALAGEM", salvo.motivoRevisao());
        assertEquals(1, salvo.avaliacoesFatoresExternos());
        assertEquals("2", salvo.avaliacoesDivergentesIds());
        assertTrue(salvo.detalhesDivergencias().contains("ID 2"));
        assertFalse(salvo.detalhesDivergencias().contains("ID 99"));
    }

    @Test
    void deveListarRelatoriosPorProdutoIdEListarTodos() {
        relatorioService.salvarRelatorio(
                "PROD-001",
                "EMBALAGEM",
                "Resumo PROD-001",
                2,
                1,
                List.of(new AvaliacaoDivergente(2L, 1, "SELL-01", "EMBALAGEM", "Caixa amassada"))
        );

        relatorioService.salvarRelatorio(
                "PROD-003",
                "LOGISTICA_ENTREGA",
                "Resumo PROD-003",
                3,
                1,
                List.of(new AvaliacaoDivergente(16L, 2, "SELL-05", "LOGISTICA_ENTREGA", "Atraso na entrega"))
        );

        List<RelatorioRevisao> porProduto = relatorioService.listarPorProdutoId("PROD-001");
        List<RelatorioRevisao> todos = relatorioService.listarTodosRelatorios();

        assertEquals(1, porProduto.size());
        assertEquals("PROD-001", porProduto.get(0).produtoId());
        assertEquals(2, todos.size());
    }
}